// 3商品分のOCR結果（画像から読み取った文字）から、比較用プロンプトを組み立てる。
// AIには画像を渡さず、OCRされた文字情報だけを渡す。
function buildComparePrompt(equipment: Equipment, ocrTexts: [string, string, string]): string {
  return `以下は、「${equipment.label}」として比較したい3商品の商品ページを
OCRで文字化した情報です。

OCRのため、文字・型式・数字等に読み取り誤りが含まれている可能性があります。
1商品につき複数枚の画面を読み取っている場合は、[画像1] [画像2] のように分かれています。

【商品① OCR結果】
${ocrTexts[0]}

【商品② OCR結果】
${ocrTexts[1]}

【商品③ OCR結果】
${ocrTexts[2]}

━━━━━━━━━━
【ステップ1　今回の指定条件を満たしているかの確認】
━━━━━━━━━━

今回のワークでは、比較する商品の条件をあらかじめ決めています。

【今回の指定条件】
${equipment.requirement}

【指定条件違反ではなく、今回まさに比較する違い】
${equipment.comparableDifferences}

詳細な比較に入る前に、必ず最初に、3商品が上の【今回の指定条件】を満たしているかを、OCR結果だけから確認してください。判定は「同じ用途の商品かどうか」ではなく、この指定条件を満たしているかどうかで行ってください。

判定は、指定条件に直接関わる記載だけを見て行ってください。価格・年式・保証・送料など、指定条件と関係のない項目がOCRで読めないことを理由に、比較を止めないでください（それらは比較表で「OCRでは確認できない」とし、【追加で確認したい情報】で案内します）。

3つのどれに当たるかを、次の順番で判断してください。

（1）指定条件に関わる内容がOCR結果から読み取れ、条件を満たしている場合
　→　ステップ2へ進んでください。
　例：商品名に「冷凍冷蔵庫」とある。または冷蔵室と冷凍室の両方の容量が書かれている　→　条件を満たす
　例：「業務用食器洗浄機」と読み取れる　→　形式（ドア型／アンダーカウンター型）に関係なく条件を満たす
　例：「製氷能力 25kg/日」と書かれている　→　条件を満たす

（2）指定条件と違う種類・仕様がはっきり書かれている場合
　→　【比較条件の確認】だけを示して終了してください。
　例：商品名が「冷蔵庫」で冷凍室の記載がない／「4口」「45kg/日」と明記されている

（3）指定条件に関わる記載が、その商品のOCR結果のどこにもない場合
　→　条件外と決めつけず、「○○か要確認」とし、その条件が確認できる画面のスクリーンショット追加を案内して終了してください。

（3）に当たる商品があるのに「満たしています」と書いてはいけません。書かれていない項目を、他の2商品と同じだろうと考えて補うことも禁止です。

誤：（商品③の製氷能力がOCR結果にないのに）「3商品とも25kg/日と読み取れるため、指定条件を満たしています」
正：「商品③は、OCRでは製氷能力を確認できないため、25kgタイプかどうかが要確認です。」

指定条件を満たさない商品が混ざっている場合は、次のような内容だけを出力して終わってください（この例文の範囲だけを書き、比較表・価格比較・容量比較・おすすめ・購入判断へは進まないでください）。

　　【比較条件の確認】

　　商品①・②は「（指定条件を満たす内容）」ですが、
　　商品③は「（読み取れた内容）」と記載されています。

　　今回のワークで指定した条件に合わないため、
　　商品③を選び直してください。

　　指定条件に合う商品を選び直し、スクリーンショットをアプリに追加してください。

判断できない場合の例：

　　【比較条件の確認】

　　商品③は、OCRでは製氷能力を確認できないため、
　　25kgタイプかどうかが要確認です。

　　製氷能力が表示されている画面のスクリーンショットを追加してください。

OCRだけで判断できない場合も、勝手に条件を満たすと決めたり、逆に条件外と決めつけたりしないでください。Web検索で型式を調べたり、メーカーの知識から補ったりすることも禁止です。

━━━━━━━━━━
【ステップ2　比較（指定条件を満たすと確認できた場合だけ）】
━━━━━━━━━━

次の順番で、簡潔に回答してください。見出しは【比較条件】【比較表】【大きな違い】【追加で確認したい情報】だけを使い、「ステップ1」「ステップ2」や「1.」「5. 最後の問いかけ」のような、この指示書の見出し・番号をそのまま書かないでください。

1. 比較条件
例：「3商品とも今回の指定条件（${equipment.label}）を満たしていると読み取れるため、比較できます。」程度の1〜2行にしてください。

2. 比較表
表は1つだけにしてください。次の形のMarkdownの表にしてください（箇条書きやスラッシュ区切りではなく、必ず表にしてください）。

| 比較項目 | 商品① | 商品② | 商品③ |
|---|---|---|---|
| 商品名・型式 |  |  |  |
| 新品／中古 |  |  |  |
| 価格 |  |  |  |
| 年式 |  |  |  |
| サイズ |  |  |  |
| 能力・容量 |  |  |  |
| 電源・設置条件 |  |  |  |
| 保証 |  |  |  |
| 送料・搬入・設置 |  |  |  |
| 要確認 |  |  |  |

この設備では、上の表に次の行も必ず追加してください。
${equipment.extraTableRows}

これ以外に重要な項目がある場合は多少変更して構いませんが、細かすぎる項目を大量に増やさないでください。年間消費電力量・冷媒・重量などは、比較上特に意味がある場合だけ入れてください。

同じ情報を、この表のあとに項目別の表や箇条書きで繰り返さないでください。表は1つだけです。

3. 大きな違い
最大3点に絞ってください。優劣やおすすめにはしないでください。

4. 追加で確認したい情報
比較表に「OCRでは確認できない」「記載を確認できない」「要確認」と書いた項目が1つでもある場合は、必ずこの【追加で確認したい情報】を書いてください。最大3点まで、「どの商品の、何が見える画面のスクリーンショットを追加すればよいか」を具体的に書いてください。1商品につき最大3枚まで画像を追加できます。

例：
・商品③：価格が表示されている画面
・商品①：電源仕様が表示されている画面

不足が特にない場合は、この見出しごと書かないでください（「不要です」「特にありません」とも書かないでください）。

5. 最後の問いかけ
最後は必ず次の文で終えてください。

「この比較を見て、価格だけでなく性能・サイズ・設置条件・保証なども踏まえ、どの商品を購入するかチームで決めてください。」

━━━━━━━━━━
【重要なルール】
━━━━━━━━━━

【「記載を確認できない」と「存在しない」を分ける】
OCR結果に情報が見つからなかった場合、「なし」と断定しないでください。「OCRでは確認できない」「記載を確認できない」「要確認」のいずれかにしてください。OCRにない＝商品に存在しない、ではありません。

誤：冷凍容量：なし
正：冷凍容量：OCRでは確認できない

「冷凍機能なし」「保証なし」などとOCR結果に明記されている場合だけ、「なし」と書けます。

【OCRの数値から新しい数字を作らない】
OCRには誤読の可能性があります。OCRに書かれた数値を、そのまま比較整理するだけにしてください。次のことをしないでください。

・足し算、引き算（例：冷凍190L＋冷蔵615L→合計805L のような合計容量の算出）
・平均、比率、単価換算
・年間電気代などへの換算
・単位変換

OCR本文に書かれていない数値を、新たに作らないでください。

【不自然な数字・型式は直さない】
桁区切りが不自然、どの数値が対象か判別しにくいなどの場合は、勝手に修正せず、OCRのまま書いたうえで「要確認」としてください。型式についても同様です。Web検索で確認することは禁止です。

誤：OCRに「398.000 円」とあるのを「398,000円」へ直して書く
正：398.000円（要確認）

読みやすく整えてよいのは、OCRが単語の途中に入れてしまった空白（例：「冷凍 冷蔵 庫」→「冷凍冷蔵庫」）までです。数字そのものは変えないでください。

【その他】
・OCR結果にない情報を推測して補わない
・Web検索して情報を追加しない
・外部知識（メーカーの知識、型式の命名規則など）で仕様を補完しない
・複数の読み方が考えられる場合に、勝手に1つへ決めない
・おすすめ順位を付けない
・「一番良い商品」を決めない
・どの商品を購入すべきかをあなたが決めない

あなたの役割は比較の整理までです。最終判断は私たちが行います。

【この設備を比較するときに一般的に見ておきたい点】
${equipment.conditionPoints}
`;
}

