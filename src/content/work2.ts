import type { FormSection, WorkConfig } from "@/lib/types";

function competitorSection(id: string, title: string): FormSection {
  return {
    id,
    title,
    fields: [
      { id: `${id}Name`, label: "店名", kind: "text" },
      { id: `${id}Price`, label: "価格帯", kind: "text" },
      {
        id: `${id}Appeal`,
        label: "看板メニュー・ウリ",
        kind: "textarea",
        rows: 3,
      },
      {
        id: `${id}Review`,
        label: "口コミでの強み・弱み",
        kind: "textarea",
        rows: 3,
      },
      {
        id: `${id}Customer`,
        label: "客層（口コミから判断）",
        kind: "textarea",
        rows: 3,
      },
    ],
  };
}

function competitorBlock(answers: Record<string, string>, id: string, n: number) {
  return `【競合店${n}】
店名：${answers[`${id}Name`] ?? ""}
価格帯：${answers[`${id}Price`] ?? ""}
看板メニュー・ウリ：${answers[`${id}Appeal`] ?? ""}
口コミでの強み・弱み：${answers[`${id}Review`] ?? ""}
客層（口コミから判断）：${answers[`${id}Customer`] ?? ""}`;
}

